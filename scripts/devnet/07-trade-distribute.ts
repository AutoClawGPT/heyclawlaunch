import { Keypair, SystemProgram, LAMPORTS_PER_SOL } from "@solana/web3.js";
import BN from "bn.js";
import { getAssociatedTokenAddressSync, TOKEN_2022_PROGRAM_ID } from "@solana/spl-token";
import { createCoin, splitFees, distribute, conn, launchWallet, sendV0, online } from "@/lib/solana";
import { PUMP_SDK, getBuyV3TokenAmountFromQuoteAmount } from "@/lib/solana/pump";
import { report } from "./lib";
import { solscanTx } from "@/lib/config";
const c = conn(), launch = launchWallet();
const uri = "https://ipfs.io/ipfs/bafkreibnxvs5lixmkj3tsxyihoswlbwn4ru5add4ikelo7er3ejeghctmi";
const { mint, sig } = await createCoin({ name: "HeyGro Trade Test", symbol: "HGTT", uri, holders: false });
const recipient = Keypair.generate();
const ssig = await splitFees(mint, recipient.publicKey);
console.log("created", mint.toBase58(), sig, "split", ssig);
const user1 = Keypair.generate();
await sendV0([SystemProgram.transfer({ fromPubkey: launch.publicKey, toPubkey: user1.publicKey, lamports: 0.6 * LAMPORTS_PER_SOL })], [launch]);
const sdk = online();
const [global, feeConfig] = await Promise.all([sdk.fetchGlobal(), sdk.fetchFeeConfig()]);
const st = await sdk.fetchBuyState(mint, user1.publicKey, TOKEN_2022_PROGRAM_ID);
const quoteAmount = new BN(0.5 * LAMPORTS_PER_SOL);
const amount = getBuyV3TokenAmountFromQuoteAmount({ global, feeConfig, mintSupply: global.tokenTotalSupply, bondingCurve: st.bondingCurve, amount: quoteAmount, curveBaseTokenBalance: st.curveBaseTokenBalance });
const buyIxs = await PUMP_SDK.buyExactQuoteInV3Instructions({ bondingCurve: st.bondingCurve, associatedUserAccountInfo: st.associatedUserAccountInfo, mint, user: user1.publicKey, amount, quoteAmount, slippage: 5, tokenProgram: TOKEN_2022_PROGRAM_ID, quoteTokenProgram: st.quoteTokenProgram });
const bsig = await sendV0(buyIxs, [user1]);
const ata = getAssociatedTokenAddressSync(mint, user1.publicKey, true, TOKEN_2022_PROGRAM_ID);
const bal = new BN((await c.getTokenAccountBalance(ata)).value.amount);
const ss = await sdk.fetchSellState(mint, user1.publicKey, TOKEN_2022_PROGRAM_ID);
const sellIxs = await PUMP_SDK.sellV3Instructions({ bondingCurve: ss.bondingCurve, mint, user: user1.publicKey, amount: bal.divn(2), quoteAmount: new BN(1), slippage: 99, tokenProgram: TOKEN_2022_PROGRAM_ID, quoteTokenProgram: ss.quoteTokenProgram });
const sellSig = await sendV0(sellIxs, [user1]);
report("07-trade", true, `buy ${solscanTx(bsig)} tokens=${bal.toString()} sell ${solscanTx(sellSig)}`);
const lBefore = await c.getBalance(launch.publicKey), rBefore = await c.getBalance(recipient.publicKey);
const d = await distribute(mint);
if (d.skipped) { report("08-distribute", false, `skipped: min ${JSON.stringify(d.min)}`); process.exit(1); }
const rAfter = await c.getBalance(recipient.publicKey);
const tx = await c.getTransaction(d.sig, { maxSupportedTransactionVersion: 0, commitment: "confirmed" });
const keys = tx!.transaction.message.getAccountKeys().staticAccountKeys.map(k => k.toBase58());
const delta = (a: string) => { const i = keys.indexOf(a); return tx!.meta!.postBalances[i] - tx!.meta!.preBalances[i]; };
const recvFees = rAfter - rBefore - 650_240;
report("08-distribute", recvFees > 0, `${solscanTx(d.sig)} recipient +${rAfter - rBefore} lamports (incl 650240 prefund, fees ${recvFees}); launch net ${delta(launch.publicKey.toBase58())} (pays fee+prefund, receives 20%) min=${d.min.minimumRequired?.toString?.()} distributable=${d.min.distributableFees?.toString?.()}`);
process.exit(0);
